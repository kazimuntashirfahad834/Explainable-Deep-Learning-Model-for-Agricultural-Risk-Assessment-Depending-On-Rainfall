# ─────────────────────────────────────────────
# STEP 3: Load Dataset
# ─────────────────────────────────────────────
import kagglehub
import os

# Download latest version of dataset
path = kagglehub.dataset_download("yakinrubaiat/bangladesh-weather-dataset")
print("Dataset downloaded to:", path)

# Check files inside downloaded folder
files = os.listdir(path)
print("Files found:", files)

# Auto-load first CSV file
csv_file = [f for f in files if f.endswith(".csv")][0]
file_path = os.path.join(path, csv_file)

df = pd.read_csv(file_path)
print(" Loaded file:", file_path)
print("Shape:", df.shape)
df.head()


# ─────────────────────────────────────────────
# STEP 4: Select Required Columns
# ─────────────────────────────────────────────
df = df[['Year', 'Month', 'tem', 'rain']]
df.columns = ['year', 'month', 'temperature', 'rainfall']

print(" Columns selected:", df.columns.tolist())
print(df.head())

# Dataset Overview Plot
plt.figure(figsize=(12, 4))
plt.plot(df['rainfall'], label='Rainfall', alpha=0.7)
plt.plot(df['temperature'], label='Temperature', alpha=0.7)
plt.legend()
plt.title("Raw Climate Data Overview")
plt.xlabel("Index")
plt.tight_layout()
plt.show()


# ─────────────────────────────────────────────
# STEP 5: Sort Data
# ─────────────────────────────────────────────
df = df.sort_values(['year', 'month']).reset_index(drop=True)
print(" Data sorted by Year and Month")

# Monthly Rainfall Trend
monthly_rain = df.groupby('month')['rainfall'].mean()

plt.figure(figsize=(8, 4))
plt.plot(monthly_rain.index, monthly_rain.values, marker='o', color='steelblue')
plt.title("Average Monthly Rainfall Pattern")
plt.xlabel("Month")
