# ─────────────────────────────────────────────
# STEP 6: Handle Missing Values
# ─────────────────────────────────────────────
print("Missing values before:", df.isnull().sum().sum())
df = df.ffill()   # Updated: replaces deprecated fillna(method='ffill')
print("Missing values after:", df.isnull().sum().sum())
print(" Missing values handled!")


# ─────────────────────────────────────────────
# STEP 7: Normalize Data
# ─────────────────────────────────────────────
scaler = MinMaxScaler()
df[['temperature', 'rainfall']] = scaler.fit_transform(
    df[['temperature', 'rainfall']]
)
print(" Data normalized with MinMaxScaler")

# Normalized Data Visualization
plt.figure(figsize=(12, 4))
plt.plot(df['temperature'], label='Temperature', alpha=0.7)
plt.plot(df['rainfall'], label='Rainfall', alpha=0.7)
plt.legend()
plt.title("Normalized Climate Variables")
plt.tight_layout()
plt.show()


# ─────────────────────────────────────────────
# STEP 8: Feature Engineering
# ─────────────────────────────────────────────
df['rain_ma3']  = df['rainfall'].rolling(3).mean().fillna(0)
df['temp_ma3']  = df['temperature'].rolling(3).mean().fillna(0)

# NEW: Additional engineered features
df['rain_ma6']      = df['rainfall'].rolling(6).mean().fillna(0)
df['temp_rain_ratio'] = df['temperature'] / (df['rainfall'] + 1e-5)
df['rainfall_lag1'] = df['rainfall'].shift(1).fillna(0)
df['rainfall_lag2'] = df['rainfall'].shift(2).fillna(0)

print(" Feature engineering complete!")
print("Features:", df.columns.tolist())


# ─────────────────────────────────────────────
# STEP 9: Create Time-Series Sequences
# ─────────────────────────────────────────────
def create_sequences(data, step=6):
    X, y = [], []
    for i in range(len(data) - step):
        X.append(data[i:i+step])
        y.append(data[i+step][1])   # rainfall target (index 1)
    return np.array(X), np.array(y)

data = df[['temperature', 'rainfall']].values

X, y = create_sequences(data, step=6)
print(f" Sequences created → X: {X.shape}, y: {y.shape}")


# ─────────────────────────────────────────────
# STEP 10: Train-Test Split
# ─────────────────────────────────────────────
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.2, shuffle=False
)
print(f" Train size: {X_train.shape[0]} | Test size: {X_test.shape[0]}")


# ─────────────────────────────────────────────
# STEP 11: Reshape for CNN
# ─────────────────────────────────────────────
X_train = X_train.reshape((X_train.shape[0], X_train.shape[1], 2))
X_test  = X_test.reshape((X_test.shape[0],  X_test.shape[1],  2))
print(f" Reshaped → X_train: {X_train.shape}, X_test: {X_test.shape}")


# ─────────────────────────────────────────────
# STEP 12: Build CNN + BiLSTM + Attention Model
# ─────────────────────────────────────────────
inputs = Input(shape=(X_train.shape[1], X_train.shape[2]))

x = Conv1D(64, 2, activation='relu')(inputs)

x = Bidirectional(LSTM(64, return_sequences=True))(x)

attention = tf.keras.layers.Attention()([x, x])

x = GlobalAveragePooling1D()(attention)

x = Dropout(0.3)(x)

x = Dense(64, activation='relu')(x)

output = Dense(1)(x)

model = Model(inputs, output)
model.compile(optimizer='adam', loss='mse', metrics=['mae'])
model.summary()
print(" Model built successfully!")


# ─────────────────────────────────────────────
# STEP 13: Train Model
# ─────────────────────────────────────────────
history = model.fit(
    X_train, y_train,
    validation_data=(X_test, y_test),
    epochs=30,
    batch_size=32,
    verbose=1
)
print(" Model training complete!")

# Training vs Validation Loss
plt.figure(figsize=(8, 4))
plt.plot(history.history['loss'],     label='Train Loss')
plt.plot(history.history['val_loss'], label='Validation Loss')
plt.legend()
plt.title("Model Training Performance")
plt.xlabel("Epochs")
plt.ylabel("Loss (MSE)")
plt.tight_layout()
plt.show()


# ─────────────────────────────────────────────
# STEP 14: Predictions
# ─────────────────────────────────────────────
y_pred = model.predict(X_test)
print(f" Predictions done → shape: {y_pred.shape}")


# ─────────────────────────────────────────────
# STEP 15: Evaluation Metrics  ← UPDATED (R² added)
# ─────────────────────────────────────────────
rmse = np.sqrt(mean_squared_error(y_test, y_pred))
