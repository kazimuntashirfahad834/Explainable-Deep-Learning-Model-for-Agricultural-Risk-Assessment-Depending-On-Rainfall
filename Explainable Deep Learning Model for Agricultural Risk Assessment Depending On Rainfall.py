def agricultural_risk_assessment(predicted_rainfall_list):
    """
    Maps predicted rainfall (normalized) →
    agricultural risk category for Bangladesh crops.
    """
    records = []
    for val in predicted_rainfall_list:
        if val < 0.2:
            records.append({
                'Predicted_Rainfall': round(val, 4),
                'Risk_Category':      'Drought Risk ',
                'Affected_Crops':     'Boro Rice, Wheat, Mustard',
                'Season':             'Rabi (Winter)',
                'Recommended_Action': 'Apply irrigation immediately'
            })
        elif val < 0.5:
            records.append({
                'Predicted_Rainfall': round(val, 4),
                'Risk_Category':      'Normal ',
                'Affected_Crops':     'All Crops Safe',
                'Season':             'All Seasons',
                'Recommended_Action': 'Standard farming practices'
            })
        elif val < 0.75:
            records.append({
                'Predicted_Rainfall': round(val, 4),
                'Risk_Category':      'Flood Risk ',
                'Affected_Crops':     'Aus Rice, Jute, Vegetables',
                'Season':             'Kharif (Monsoon)',
                'Recommended_Action': 'Improve drainage, protect seedlings'
            })
        else:
            records.append({
                'Predicted_Rainfall': round(val, 4),
                'Risk_Category':      'Extreme Flood Risk ',
                'Affected_Crops':     'All Crops (severe loss expected)',
                'Season':             'Peak Monsoon',
                'Recommended_Action': 'Emergency protocol — evacuate crops'
            })
    return pd.DataFrame(records)

